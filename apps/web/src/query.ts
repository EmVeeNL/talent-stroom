import { MutationCache, QueryCache, QueryClient, queryOptions } from "@tanstack/react-query";
import type { Locale } from "@talentstroom/i18n";
import type { QueryKey } from "@tanstack/react-query";
import { ProblemDetails, ValidationProblem, PROBLEMS } from "@talentstroom/contracts";
import { RequestError, isAborted } from "./auth.ts";
import type { OrganizationList, Transport } from "./auth.ts";

// Only reviewed, non-personal result variants belong in a key. Free-text filters do not.
interface SafeParameters {
  page?: number;
  sort?: "created-desc" | "created-asc";
}
export const queryKeys = {
  session: ["session"] as const,
  organizations: ["me", "organizations"] as const,
  org: (organizationId: string, resource: string, operation: string, parameters: SafeParameters = {}) =>
    ["org", organizationId, resource, operation, parameters] as const,
};
export class ProblemError extends RequestError {
  readonly type: string | undefined;
  readonly requestId: string | undefined;
  readonly fields: { path: "name"; code: "too_small" | "too_big" | "invalid_type" }[] = [];
  constructor(response: Response, body: unknown) {
    super(response.status);
    if (!response.headers.get("content-type")?.includes("application/problem+json")) return;
    const problem = ProblemDetails.safeParse(body);
    if (!problem.success || problem.data.status !== response.status) return;
    this.type = Object.values(PROBLEMS).find((entry) => entry.type === problem.data.type)?.type;
    // Request IDs generated by the API are UUIDs; never retain arbitrary server strings.
    if (/^[\da-f]{8}-(?:[\da-f]{4}-){3}[\da-f]{12}$/i.test(problem.data.requestId))
      this.requestId = problem.data.requestId;
    const validation = ValidationProblem.safeParse(body);
    if (validation.success) {
      for (const field of validation.data.errors) {
        if (
          field.path === "name" &&
          (field.message === "too_small" || field.message === "too_big" || field.message === "invalid_type")
        )
          this.fields.push({ path: "name", code: field.message });
      }
    }
  }
}
export const problemError = (response: Response, body: unknown) => new ProblemError(response, body);
export function retryQuery(failureCount: number, error: unknown) {
  return (
    failureCount < 1 &&
    !isAborted(error) &&
    (error instanceof TypeError || (error instanceof RequestError && (error.status === 0 || error.status >= 500)))
  );
}
function safeError(error: unknown) {
  return error instanceof RequestError || isAborted(error) ? error : new RequestError(0);
}
function aborted(): never {
  throw new DOMException("Aborted", "AbortError");
}
export interface Bootstrap {
  session: object | null;
  data?: OrganizationList;
}
interface Handlers {
  onExpired?: () => void;
  onBarrier?: (blocked: boolean) => void;
  onLoaded?: (result: Bootstrap) => void;
  onRecoveryError?: (error: unknown) => void;
  onScopeChanged?: () => void;
}

function identity(value: object) {
  const user: unknown = "user" in value ? value.user : undefined;
  if (!user || typeof user !== "object") return undefined;
  // Better Auth supplies an id; the email fallback also supports older session fixtures.
  return "id" in user ? user.id : "email" in user ? user.email : undefined;
}

/** Private to one mounted app. No persistence, broadcast data, or module-level client. */
export function createDataLayer(initialHandlers: Handlers = {}) {
  let handlers = initialHandlers;
  let generation = 0;
  let blocked = false;
  let activeOrganizationId: string | undefined;
  let membershipIds = new Set<string>();
  let work = new AbortController();
  let lifecycle: AbortController | undefined;
  let currentTransport: Transport | undefined;
  let resolved: Bootstrap | undefined;
  const client = new QueryClient({
    queryCache: new QueryCache({
      onError: (error, query) => {
        if (error instanceof RequestError && error.status === 401) expire();
        else if (
          query.queryKey[0] === "org" &&
          error instanceof RequestError &&
          (error.status === 403 || error.status === 409)
        )
          handlers.onScopeChanged?.();
      },
    }),
    mutationCache: new MutationCache(),
    defaultOptions: {
      queries: {
        staleTime: 30_000,
        gcTime: 300_000,
        retry: retryQuery,
        refetchOnWindowFocus: true,
        refetchOnReconnect: true,
      },
      mutations: { retry: false, networkMode: "always", gcTime: 0 },
    },
  });
  function discard() {
    generation++;
    resolved = undefined;
    activeOrganizationId = undefined;
    membershipIds.clear();
    work.abort();
    work = new AbortController();
    currentTransport?.cancel();
    // Cancellation happens synchronously; callers of a transition also await its completion.
    const cancelled = client.cancelQueries();
    client.clear();
    return cancelled;
  }
  function expire() {
    lifecycle?.abort();
    void discard();
    blocked = false;
    handlers.onExpired?.();
    handlers.onBarrier?.(false);
  }
  function guard(captured: number, signal: AbortSignal) {
    if (generation !== captured || signal.aborted) aborted();
  }
  function requireScope(orgId: string) {
    if (blocked || orgId !== activeOrganizationId) aborted();
  }
  function sessionOptions(transport: Transport) {
    const captured = generation;
    const transportSignal = transport.signal;
    return queryOptions({
      queryKey: queryKeys.session,
      staleTime: 0,
      retry: false,
      queryFn: async ({ signal }) => {
        const combined = AbortSignal.any([signal, transportSignal, work.signal]);
        try {
          const result = await transport.auth("get-session", undefined, "nl-NL", combined);
          guard(captured, combined);
          return result && typeof result === "object" && "user" in result ? result : null;
        } catch (error) {
          throw safeError(error);
        }
      },
    });
  }
  function organizationOptions(transport: Transport) {
    const captured = generation;
    const transportSignal = transport.signal;
    return queryOptions({
      queryKey: queryKeys.organizations,
      staleTime: 0,
      retry: false,
      queryFn: async ({ signal }) => {
        const combined = AbortSignal.any([signal, transportSignal, work.signal]);
        try {
          const result = await transport.api.GET("/v1/me/organizations", { signal: combined, cache: "no-store" });
          guard(captured, combined);
          if (!result.data) throw problemError(result.response, result.error);
          return result.data;
        } catch (error) {
          throw safeError(error);
        }
      },
    });
  }
  async function bootstrap(transport: Transport): Promise<Bootstrap> {
    currentTransport = transport;
    const captured = generation;
    const session = await client.fetchQuery(sessionOptions(transport));
    if (captured !== generation) aborted();
    if (!session) {
      if (activeOrganizationId) await discard();
      activeOrganizationId = undefined;
      return { session: null };
    }
    const data = await client.fetchQuery(organizationOptions(transport));
    if (captured !== generation) aborted();
    const previous = activeOrganizationId;
    membershipIds = new Set(data.organizations.map((org) => org.organizationId));
    const next =
      data.activeOrganizationId && membershipIds.has(data.activeOrganizationId) ? data.activeOrganizationId : undefined;
    if (previous && previous !== next) {
      await discard();
      return bootstrap(transport);
    }
    activeOrganizationId = next;
    resolved = { session, data };
    return resolved;
  }
  /** Inspect cookie context without changing the active scope or exposing new data to the view. */
  async function revalidate(transport: Transport) {
    if (blocked || !resolved?.session || !resolved.data) return;
    const previousSession = resolved.session;
    const previousData = resolved.data;
    const captured = generation;
    const signal = work.signal;
    const session = await client.fetchQuery(sessionOptions(transport));
    guard(captured, signal);
    if (!session) {
      expire();
      return;
    }
    const resetScope = () => {
      // Revoke cached scope synchronously, before a different identity can be rendered.
      void discard();
      handlers.onScopeChanged?.();
    };
    if (identity(session) !== identity(previousSession)) {
      resetScope();
      return;
    }
    const data = await client.fetchQuery(organizationOptions(transport));
    guard(captured, signal);
    const changed =
      data.activeOrganizationId !== previousData.activeOrganizationId ||
      previousData.organizations.some(
        (old) =>
          !data.organizations.some(
            (next) =>
              next.organizationId === old.organizationId &&
              next.membershipId === old.membershipId &&
              next.role === old.role,
          ),
      );
    if (changed) {
      resetScope();
      return;
    }
    membershipIds = new Set(data.organizations.map((org) => org.organizationId));
    resolved = { session, data };
    handlers.onLoaded?.(resolved);
  }
  async function mutation<T>(key: QueryKey, run: () => Promise<T>) {
    // Credentials and form values stay in the invocation closure, never Mutation variables/keys/meta.
    const entry = client.getMutationCache().build(client, { mutationKey: key, mutationFn: run, retry: false });
    try {
      return await entry.execute(undefined);
    } catch (error) {
      throw safeError(error);
    } finally {
      client.getMutationCache().remove(entry);
    }
  }
  async function transition<T>(
    transport: Transport,
    key: QueryKey,
    run: (signal: AbortSignal) => Promise<T>,
    reload = true,
  ) {
    if (blocked) aborted();
    blocked = true;
    handlers.onBarrier?.(true);
    currentTransport = transport;
    lifecycle = new AbortController();
    const signal = lifecycle.signal;
    await discard();
    const captured = generation;
    let result: { value: T } | undefined;
    let failure: unknown;
    try {
      result = { value: await mutation(key, () => run(signal)) };
      guard(captured, signal);
    } catch (error) {
      if (captured !== generation || signal.aborted) aborted();
      failure = error;
      if (error instanceof RequestError && error.status === 401) {
        expire();
        throw error;
      }
    } finally {
      // Remove the transition mutation's result and any state a callback attempted to insert.
      if (captured === generation) client.clear();
    }
    try {
      if (reload) {
        const loaded = await bootstrap(transport);
        handlers.onLoaded?.(loaded);
      }
    } catch (error) {
      if (!isAborted(error) && !(error instanceof RequestError && error.status === 401))
        handlers.onRecoveryError?.(error);
      throw error;
    } finally {
      if (captured === generation) {
        blocked = false;
        lifecycle = undefined;
        handlers.onBarrier?.(false);
      }
    }
    if (failure) throw failure;
    if (!result) aborted();
    return result.value;
  }
  function orgQuery<T>(
    orgId: string,
    resource: string,
    operation: string,
    read: (signal: AbortSignal) => Promise<T>,
    parameters: SafeParameters = {},
  ) {
    requireScope(orgId);
    const captured = generation;
    const workSignal = work.signal;
    return queryOptions({
      queryKey: queryKeys.org(orgId, resource, operation, parameters),
      queryFn: async ({ signal }) => {
        requireScope(orgId);
        const combined = AbortSignal.any([signal, workSignal]);
        try {
          const result = await read(combined);
          guard(captured, combined);
          requireScope(orgId);
          return result;
        } catch (error) {
          throw safeError(error);
        }
      },
    });
  }
  async function orgMutation<T>(
    orgId: string,
    resource: string,
    operation: string,
    run: (signal: AbortSignal) => Promise<T>,
    apply?: (result: T) => void,
  ) {
    requireScope(orgId);
    const captured = generation;
    const signal = work.signal;
    try {
      const result = await mutation(queryKeys.org(orgId, resource, operation), () => run(signal));
      guard(captured, signal);
      requireScope(orgId);
      apply?.(result);
      guard(captured, signal);
      requireScope(orgId);
      await client.invalidateQueries({ queryKey: ["org", orgId] });
      return result;
    } catch (error) {
      if (captured === generation && error instanceof RequestError) {
        if (error.status === 401) expire();
        else if (error.status === 403 || error.status === 409) handlers.onScopeChanged?.();
      }
      throw error;
    }
  }
  async function changeOrganization(transport: Transport, change: { orgId: string } | { name: string }) {
    if ("orgId" in change && !membershipIds.has(change.orgId)) throw new RequestError(403);
    const key =
      "orgId" in change ? queryKeys.org(change.orgId, "organizations", "switch") : ["me", "organizations", "create"];
    return transition(transport, key, async (signal) => {
      const result =
        "orgId" in change
          ? await transport.api.POST("/v1/organizations/{orgId}/switch", {
              params: { path: { orgId: change.orgId } },
              signal,
            })
          : await transport.api.POST("/v1/organizations", { body: { name: change.name }, signal });
      signal.throwIfAborted();
      if (!result.data) throw problemError(result.response, result.error);
    });
  }
  async function signIn(
    transport: Transport,
    body: { email: string; password: string },
    locale: Locale,
    externalSignal?: AbortSignal,
  ) {
    if (blocked) aborted();
    const captured = generation;
    const signal = AbortSignal.any([work.signal, ...(externalSignal ? [externalSignal] : [])]);
    const result = await mutation(["session", "sign-in"], () => transport.auth("sign-in/email", body, locale, signal));
    guard(captured, signal);
    return result;
  }
  async function authSubmit(
    transport: Transport,
    endpoint: string,
    body?: Record<string, string>,
    locale: Locale = "nl-NL",
    externalSignal?: AbortSignal,
  ) {
    if (blocked) aborted();
    const captured = generation;
    const signal = AbortSignal.any([work.signal, ...(externalSignal ? [externalSignal] : [])]);
    const result = await mutation(["session", "auth-submit"], () => transport.auth(endpoint, body, locale, signal));
    guard(captured, signal);
    return result;
  }
  return {
    client,
    bootstrap,
    revalidate,
    sessionOptions,
    organizationOptions,
    orgQuery,
    orgMutation,
    transition,
    changeOrganization,
    signIn,
    authSubmit,
    expire,
    reset: () => {
      lifecycle?.abort();
      lifecycle = undefined;
      blocked = false;
      handlers.onBarrier?.(false);
      return discard();
    },
    setHandlers: (next: Handlers) => {
      handlers = next;
    },
    get activeOrganizationId() {
      return activeOrganizationId;
    },
  };
}
export type DataLayer = ReturnType<typeof createDataLayer>;
